/**
  The answer sheet: every activity item's prompt and its answers on every
  retake, as markdown. `npm run answers` writes it to docs/answer-sheet.md,
  and a test checks that file is up to date with the lesson files.
 */
import { CONFIG } from './config';
import { FINAL_TEST, finalQuestions } from './finalTest';
import { LESSON_SPECS, activityQuestions } from './lessons';
import type { LessonNumber } from './lessonSchema';
import type { ItemSpec, Part, Question } from './schema';

function slotInWords(key: number, slot: { parent: number | null; side: string | null }): string {
  return slot.parent === null ? `${key} → root` : `${key} → ${slot.side} of ${slot.parent}`;
}

// One part's answer in words.
export function answerInWords(part: Part): string {
  switch (part.type) {
    case 'pick':
      return part.options[part.answer] as string;
    case 'click':
      return typeof part.answer === 'number' ? String(part.answer) : part.answer.join(', ');
    case 'order':
      return part.answer.join(' ');
    case 'place':
      return part.answer.map((slot, i) => slotInWords(part.keys[i] as number, slot)).join('; ');
  }
}

// A question's answers in words, each part labelled when it has a label.
export function questionAnswer(question: Question): string {
  return question.parts
    .map((part) => {
      if (part.label === '') return answerInWords(part);
      // "Which case is this? Leaf", but "Path: 50, 30, 20".
      return `${part.label}${part.label.endsWith('?') ? '' : ':'} ${answerInWords(part)}`;
    })
    .join(' · ');
}

// Escape the characters that would break a markdown table cell.
function cell(text: string): string {
  return text.replace(/\|/g, '\\|');
}

export function answerSheet(): string {
  const retakes = CONFIG.retakeOffsets.map((_, retake) => retake);
  const lines: string[] = [
    '# Answer sheet',
    '',
    'Generated by `npm run answers` from the lesson files in `src/content/data`. Do not edit it by hand: change the lesson files and run the command again. A test fails if this file is out of date.',
    '',
    `Each retake shifts every key: ${CONFIG.retakeOffsets.map((offset, retake) => `retake ${retake} by ${offset >= 0 ? '+' : ''}${offset}`).join(', ')}.`,
    '',
  ];

  // One section: every item's prompt, then its answers on each retake.
  const section = (items: readonly ItemSpec[], questionsFor: (retake: number) => Question[]) => {
    const byRetake = retakes.map(questionsFor);
    items.forEach((item, i) => {
      const first = byRetake[0]?.[i] as Question;
      const tags = [item.outcome, first.deleteCase === undefined ? '' : `delete case: ${first.deleteCase}`]
        .filter((tag) => tag !== '')
        .join(', ');
      lines.push(`### ${i + 1}. \`${item.id}\` (${tags})`, '');
      if (first.intro !== undefined) lines.push(`*${first.intro}*`, '');
      lines.push(first.prompt, '', '| Retake | Answer |', '|---|---|');
      for (const retake of retakes) {
        lines.push(`| ${retake} | ${cell(questionAnswer(byRetake[retake]?.[i] as Question))} |`);
      }
      lines.push('');
    });
  };

  for (const n of [1, 2, 3, 4, 5] as LessonNumber[]) {
    const spec = LESSON_SPECS[n];
    lines.push(`## Lesson ${n}: ${spec.title}`, '', `Activity: ${spec.activity.title}.`, '');
    section(spec.activity.items, (retake) => activityQuestions(n, retake));
  }

  lines.push(`## ${FINAL_TEST.title}`, '', FINAL_TEST.summary, '');
  section(FINAL_TEST.items, finalQuestions);

  lines.push(
    '### Results',
    '',
    'An outcome is secure when every item for it is right. The descriptor is the first whose score the student reaches (and whose required items are right):',
    '',
    '| Descriptor | Score | Also needs |',
    '|---|---|---|',
    ...FINAL_TEST.descriptors.map((d, i) => {
      const top = i === 0 ? FINAL_TEST.items.length : (FINAL_TEST.descriptors[i - 1] as { min: number }).min - 1;
      return `| ${d.name} | ${d.min} to ${top} | ${(d.requires ?? []).map((id) => `\`${id}\``).join(', ') || 'nothing more'} |`;
    }),
    '',
  );

  return lines.join('\n');
}